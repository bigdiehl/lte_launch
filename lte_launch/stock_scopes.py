"""The body's scopes, carried into a stock include.

A stock include is one ``ros2 launch`` process, so ``ros_params()`` and
``ros_remaps()`` cannot be put on its nodes' command lines one by one. Instead
a small wrapper launch file applies them the way stock itself would, then
includes the target:

    GroupAction([SetParametersFromFile(f), SetRemap(a, b),
                 IncludeLaunchDescription(target)])

``namespace()`` is deliberately not applied: a stock file places its own
nodes (pass its ``namespace`` argument, if it has one).

and ``ros2 launch <wrapper> name:=value ...`` runs instead of the target. The
arguments stay on that command line (a ``--dry-run`` shows them); the
wrapper passes each on to the target by name. Universal (``/**``) config-file sections go in
too, over the scopes, as for our own nodes; a section with any other pattern
cannot be matched against nodes whose names we do not know, so it does not.

Parameters travel as a parameter file (``SetParametersFromFile``), not
``SetParameter``, so their types survive (``SetParameter`` hands rcl text:
the string ``"1"`` would arrive as an int). As stock, a node's own
``parameters=`` still win over these, and these remappings come first, so
they win over its own ``remappings=``.

Importable without ROS: the wrapper is text; ROS reads it.
"""

from __future__ import annotations

import os
from typing import Any

import yaml

TEMPLATE = '''\
# Generated by lte-launch: {target}, in the including body's scopes.
# parameters: {params}
# remappings: {remaps}

from launch import LaunchDescription
from launch.actions import GroupAction, IncludeLaunchDescription
from launch.launch_description_sources import AnyLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import SetParametersFromFile, SetRemap


def generate_launch_description():
{find}    return LaunchDescription([
        GroupAction([
{actions}            IncludeLaunchDescription(
                AnyLaunchDescriptionSource(path),
                launch_arguments=[(n, LaunchConfiguration(n)) for n in {names!r}],
            ),
        ]),
    ])
'''


def scopes(run, label: str) -> tuple[dict[str, Any], dict[str, str]]:
    """-> (parameters, remappings) a stock include started here
    gets: the body's scopes, then universal config-file sections over them.
    Each such section records ``label`` as what it matched."""
    params, remaps = dict(run.scope_params), dict(run.scope_remaps)
    for section in run.ros.sections:
        if section.universal:
            section.matched.append(label)
            params.update(section.params)
            remaps.update(section.remaps)
    return params, remaps


def wrapper(
    package: str | None,
    file: str,
    *,
    params: dict[str, Any],
    remaps: dict[str, str],
    directory: str,
    stem: str,
    args: list[str] = (),
) -> str | None:
    """Write the wrapper launch file for ``ros2 launch [package] file``; -> its
    path, or None when there is nothing to apply (run the target as it is).
    ``args``: the names of the arguments given on the command line, passed on
    by name (stock checks an include's required arguments by name)."""
    if not params and not remaps:
        return None
    os.makedirs(directory, exist_ok=True)
    path = _unique(directory, stem, ".launch.py")
    actions = []
    if params:
        params_path = path[: -len(".launch.py")] + ".params.yaml"
        with open(params_path, "w") as f:
            yaml.safe_dump({"/**": {"ros__parameters": params}}, f, sort_keys=False)
        actions.append(f"SetParametersFromFile({params_path!r})")
    actions += [f"SetRemap({src!r}, {dst!r})" for src, dst in remaps.items()]
    if package:
        target = f"{package} {file}"
        find = (
            "    from ros2launch.api import get_share_file_path_from_package\n\n"
            "    path = get_share_file_path_from_package(\n"
            f"        package_name={package!r}, file_name={file!r}\n"
            "    )\n"
        )
    else:
        target = os.path.abspath(file)
        find = f"    path = {target!r}\n"
    text = TEMPLATE.format(
        target=target,
        params=repr(params) if params else "-",
        remaps=repr(remaps) if remaps else "-",
        find=find,
        names=list(args),
        actions="".join(f"            {a},\n" for a in actions),
    )
    with open(path, "w") as f:
        f.write(text)
    return path


def _unique(directory: str, stem: str, suffix: str) -> str:
    """``<directory>/<stem><suffix>``, numbered if taken: a second include
    must not rewrite a file the first ``ros2 launch`` may not have read yet."""
    path, n = os.path.join(directory, stem + suffix), 1
    while os.path.exists(path):
        n += 1
        path = os.path.join(directory, f"{stem}.{n}{suffix}")
    return path
